/**
 * A device-wide running total that one or more [Achievement]s are measured against: shared, so "finish 10 / 50 / 100
 * games" is one stored number, not three. Each moves as the game it counts happens (`AchievementEngine`), never twice
 * for one event.
 */
enum class AchievementCounter(
    override val id: String,
    /** How the cloud save and progress files combine this counter from several devices. */
    val cloudMerge: CounterMerge = CounterMerge.SUM,
) : StoredId {
    /** Games player 1 has finished: counted when they're placed. */
    GAMES_PLAYED("GAMES_PLAYED"),

    /** Games player 1 has won. */
    GAMES_WON("GAMES_WON"),

    /** Player 1's wins in a row: back to 0 the moment another player wins. */
    WIN_STREAK("WIN_STREAK", cloudMerge = CounterMerge.LATEST),

    /** Opponents' pawns player 1 has captured. */
    CAPTURES("CAPTURES"),

    /** Player 1's pawns brought home. */
    PAWNS_HOME("PAWNS_HOME"),

    /** Player 1's rolls of the die. */
    DIE_ROLLS("DIE_ROLLS"),

    /** Player 1's rolls of a 6. */
    SIXES_ROLLED("SIXES_ROLLED"),

    /** The squares player 1's pawns have moved: a pawn out of its yard moves one, onto its start square. */
    SQUARES_MOVED("SQUARES_MOVED"),

    /** Games player 1 has finished last in. */
    LAST_PLACES("LAST_PLACES"),

    /** Player 1's losses in a row: up one each time another player wins, back to 0 with a win of theirs. */
    LOSS_STREAK("LOSS_STREAK", cloudMerge = CounterMerge.LATEST),

    /**
     * The seconds the app has been in front of the player: Statistics' time played, counted by
     * `net.zodac.ludoplus.app.PlayTimeTracker`. No achievement is measured against it, and it stays out of
     * [net.zodac.ludoplus.data.achievements.AchievementsState], so its saves never move the achievements.
     */
    PLAY_SECONDS("PLAY_SECONDS"),
}

/** How the cloud save and progress files combine one [AchievementCounter] from several devices. */
enum class CounterMerge {
    /** Each device's own share, added up: games played on two phones count on both. */
    SUM,

    /** The value from the device that wrote it most recently: a streak runs on one timeline, not one per device. */
    LATEST,
}

/**
 * The longest an [Achievement.title] may be. The unlock banner shows a title on ONE line, shrunk to no smaller than
 * 11sp and never wrapped, so a title has to fit its column at that size: 38 characters fits at 11sp on the
 * maintainer's phone (about 345dp wide) with a character or so to spare. A longer title is a project-rule breach:
 * shorten it (`CLAUDE.md`). `AchievementTextTest` enforces it.
 *
 * That is the English figure. A translation may set its own `achievement_title_max_length`, which the test then holds
 * that language's titles to; one that leaves it out gets this.
 */
const val MAX_ACHIEVEMENT_TITLE_LENGTH = 38

/**
 * What an achievement is about, and the order those themes are shown in, so a ladder's rungs sit together.
 *
 * Every [EASTER_EGGS] achievement is [AchievementVisibility.HIDDEN] and outside [Achievement.COMPLETIONIST]: an
 * unlocked one counts towards the earned figure on the Achievements page, but never its total, so a player with
 * everything reads more earned than the total. That is intended.
 */
enum class AchievementCategory(val label: StringResource) {
    MILESTONES(Res.string.category_milestones),
    THE_DIE(Res.string.category_the_die),
    CAPTURES(Res.string.category_captures),
    RACING(Res.string.category_racing),
    WINNING(Res.string.category_winning),
    MISFORTUNE(Res.string.category_misfortune),
    MISCELLANEOUS(Res.string.category_miscellaneous),
    COLLECTION(Res.string.category_collection),
    EASTER_EGGS(Res.string.category_easter_eggs),
}

/** How a locked achievement shows progress, and how eagerly progress is worth announcing. */
enum class ProgressStyle {
    /** One-shot: there is nothing to count. */
    NONE,

    /** Counts up and never falls. Announced only at quarter marks, or every [Achievement.progressStepSize]. */
    CUMULATIVE,

    /** Can collapse back to zero at any time, so every step forward is announced. */
    STREAK,
}

/** How much of a locked achievement is shown before it's earned. */
enum class AchievementVisibility {
    /** Title and description both shown from the start. */
    NORMAL,

    /** Title shown, description "???" until earned. */
    HIDDEN,
}

/**
